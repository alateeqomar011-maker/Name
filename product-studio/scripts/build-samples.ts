// Builds the landing-page examples by running Vitrine's real pipeline (local
// background removal + studio compositing) on the photos in samples/source.
//
//   npm run samples:build
//
// Source photos: perfume/serum/jar/mug are 3D-rendered stand-in products shot
// like phone photos; espresso.jpg is a real photograph (Rachel Michetti, CC0,
// via the scikit-image sample data). Every "after" image is genuine output.

import fs from "node:fs";
import path from "node:path";
import sharp from "sharp";
import { renderRecipe, type RenderRecipe } from "@/server/imaging/compose";
import { removeBackground } from "@/server/imaging/segment";
import type { AspectId, Layout } from "@/lib/studio-styles";
import { getStyle } from "@/lib/studio-styles";

interface SampleSpec {
  id: string;
  name: string;
  layout: Layout;
  styles: { id: string; variation?: number }[];
}

const SAMPLES: SampleSpec[] = [
  { id: "perfume", name: "Aura Eau de Parfum", layout: "standing", styles: [{ id: "noir-gloss" }, { id: "marble" }, { id: "champagne" }, { id: "pastel-podium", variation: 1 }, { id: "ramadan-nights" }, { id: "marketplace-white" }] },
  { id: "serum", name: "Noor Vitamin C Serum", layout: "standing", styles: [{ id: "sunlit-shadows" }, { id: "studio-white", variation: 1 }, { id: "color-pop", variation: 1 }, { id: "linen" }, { id: "autumn-amber" }, { id: "marketplace-white" }] },
  { id: "jar", name: "Lune Night Cream", layout: "standing", styles: [{ id: "pastel-podium" }, { id: "marble", variation: 2 }, { id: "spring-bloom" }, { id: "velvet", variation: 1 }, { id: "soft-gray" }, { id: "marketplace-white" }] },
  { id: "mug", name: "Kaffa Roasters Mug", layout: "standing", styles: [{ id: "wood-table" }, { id: "concrete" }, { id: "geometric" }, { id: "holiday-glow", variation: 1 }, { id: "summer-sun", variation: 2 }, { id: "marketplace-white" }] },
  { id: "espresso", name: "Espresso cup (real photo)", layout: "flatlay", styles: [{ id: "paper-sand" }, { id: "noir-gloss" }, { id: "linen", variation: 1 }, { id: "color-pop", variation: 2 }] },
];

const ROOT = process.cwd();
const SRC = path.join(ROOT, "samples/source");
const OUT = path.join(ROOT, "public/samples");
const ASPECT: AspectId = "4:5";

async function main() {
  fs.mkdirSync(OUT, { recursive: true });
  const manifest: Record<string, unknown>[] = [];
  for (const s of SAMPLES) {
    const file = path.join(SRC, `${s.id}.jpg`);
    if (!fs.existsSync(file)) continue;
    const t0 = Date.now();
    const cut = await removeBackground(fs.readFileSync(file));
    const dir = path.join(OUT, s.id);
    fs.mkdirSync(dir, { recursive: true });
    await sharp(file).resize(900, 1125, { fit: "cover" }).jpeg({ quality: 82, mozjpeg: true }).toFile(path.join(dir, "before.jpg"));
    await sharp(cut.png).resize(800, 800, { fit: "inside", withoutEnlargement: true }).webp({ quality: 88, alphaQuality: 92 }).toFile(path.join(dir, "cutout.webp"));
    const cm = await sharp(path.join(dir, "cutout.webp")).metadata();
    const renders: { style: string; name: string; src: string }[] = [];
    for (const st of s.styles) {
      const recipe: RenderRecipe = { version: 1, styleId: st.id, aspect: ASPECT, layout: s.layout, variation: st.variation ?? 0, cutoutAssetId: "sample" };
      const out = await renderRecipe({ recipe, product: { data: cut.png, width: cut.width, height: cut.height }, longEdge: 1125 });
      await sharp(out.data).flatten({ background: "#ffffff" }).jpeg({ quality: 82, mozjpeg: true }).toFile(path.join(dir, `${st.id}.jpg`));
      renders.push({ style: st.id, name: getStyle(st.id)?.name ?? st.id, src: `/samples/${s.id}/${st.id}.jpg` });
    }
    manifest.push({
      id: s.id,
      name: s.name,
      before: `/samples/${s.id}/before.jpg`,
      cutout: { src: `/samples/${s.id}/cutout.webp`, width: cm.width, height: cm.height },
      renders,
    });
    console.log(`✓ ${s.id} (${cut.method}) in ${((Date.now() - t0) / 1000).toFixed(1)}s`);
  }
  const ts = `// Generated by scripts/build-samples.ts — real Vitrine pipeline output.\nexport const SAMPLES = ${JSON.stringify(manifest, null, 2)} as const;\n\nexport type Sample = (typeof SAMPLES)[number];\n`;
  fs.writeFileSync(path.join(ROOT, "src/lib/samples.ts"), ts);
  console.log("manifest written to src/lib/samples.ts");
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
