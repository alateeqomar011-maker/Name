"""Private recording storage. Files live under var/recordings/<user>/<recording>/ and are only ever
served to their owner. Deleting a recording deletes its files immediately."""
from __future__ import annotations

import shutil
import uuid
from pathlib import Path

from . import db
from .audio.io import AudioError, decode, encode_m4a, peaks, probe
from .config import PlanLimits, settings

ALLOWED_KINDS = {"practice", "upload", "transform"}
ORIGINAL = "original"
PLAYBACK = "play.m4a"


class StorageError(ValueError):
    pass


def rec_dir(user_id: str, rec_id: str) -> Path:
    # ids are generated by us (hex uuids); never derived from user input
    return settings.recordings_dir / user_id / rec_id


def usage(user_id: str) -> dict:
    row = db.one("SELECT COUNT(*) AS n, COALESCE(SUM(size_bytes), 0) AS b FROM recordings WHERE user_id = ?", user_id)
    return {"recordings": row["n"], "bytes": row["b"]}


def _safe_ext(name: str | None, fmt: str | None) -> str:
    ext = Path(name or "").suffix.lower().lstrip(".")
    if ext in {"wav", "mp3", "m4a", "aac", "ogg", "oga", "opus", "webm", "flac", "mp4", "3gp", "amr", "caf"}:
        return ext
    return {"wav": "wav", "mp3": "mp3", "ogg": "ogg", "matroska,webm": "webm", "flac": "flac"}.get(fmt or "", "bin")


def save_upload(user_id: str, plan: PlanLimits, data: bytes, *, kind: str, filename: str | None,
                title: str | None, surah: int | None, ayah_from: int | None, ayah_to: int | None,
                max_seconds: float | None = None) -> dict:
    if kind not in ALLOWED_KINDS - {"transform"}:
        raise StorageError("Unknown recording type.")
    if len(data) > plan.max_upload_mb * 1024 * 1024:
        raise StorageError(f"The file is larger than {plan.max_upload_mb} MB.")
    u = usage(user_id)
    if u["recordings"] >= plan.max_recordings:
        raise StorageError(f"You have reached the limit of {plan.max_recordings} saved recordings. Delete some to continue.")
    if u["bytes"] + len(data) > plan.max_storage_mb * 1024 * 1024:
        raise StorageError(f"Your storage ({plan.max_storage_mb} MB) is full. Delete some recordings to continue.")
    try:
        info = probe(data)
        limit = max_seconds or max(plan.max_tajweed_seconds, plan.max_transform_seconds)
        y = decode(data, sr=16000, max_seconds=limit)
    except AudioError as e:
        raise StorageError(str(e)) from e
    duration = y.size / 16000
    if duration < 0.5:
        raise StorageError("The recording is too short.")
    playback = encode_m4a(y, 16000, bitrate="64k")
    return _store(user_id, kind, data, _safe_ext(filename, info.get("format")), playback, duration,
                  title=title, surah=surah, ayah_from=ayah_from, ayah_to=ayah_to,
                  meta={"peaks": peaks(y, 400), "codec": info.get("codec"), "sampleRate": info.get("sample_rate")},
                  original_name=filename)


def save_generated(user_id: str, kind: str, wav: bytes, playback_wave, sr: int, *, title: str,
                   surah, ayah_from, ayah_to, reciter_id, source_recording_id, meta: dict) -> dict:
    playback = encode_m4a(playback_wave, sr, bitrate="96k")
    return _store(user_id, kind, wav, "wav", playback, playback_wave.size / sr, title=title, surah=surah,
                  ayah_from=ayah_from, ayah_to=ayah_to, reciter_id=reciter_id,
                  source_recording_id=source_recording_id, meta=meta)


def _store(user_id, kind, original: bytes, ext: str, playback: bytes, duration: float, *, title=None,
           surah=None, ayah_from=None, ayah_to=None, reciter_id=None, source_recording_id=None, meta=None,
           original_name=None) -> dict:
    rid = uuid.uuid4().hex
    d = rec_dir(user_id, rid)
    d.mkdir(parents=True, exist_ok=False)
    (d / f"{ORIGINAL}.{ext}").write_bytes(original)
    (d / PLAYBACK).write_bytes(playback)
    size = len(original) + len(playback)
    db.run("INSERT INTO recordings(id, user_id, kind, title, surah, ayah_from, ayah_to, reciter_id, source_recording_id,"
           " created_at, duration_s, size_bytes, original_name, original_ext, meta) VALUES (?,?,?,?,?,?,?,?,?,?,?,?,?,?,?)",
           rid, user_id, kind, (title or "")[:120] or None, surah, ayah_from, ayah_to, reciter_id, source_recording_id,
           db.now(), duration, size, (original_name or "")[:200] or None, ext, db.jdump(meta or {}))
    return get(user_id, rid)


def get(user_id: str, rid: str) -> dict | None:
    row = db.one("SELECT * FROM recordings WHERE id = ? AND user_id = ?", rid, user_id)
    if row is None:
        return None
    d = dict(row)
    d["meta"] = db.jload(d["meta"], {})
    return d


def original_path(rec: dict) -> Path:
    return rec_dir(rec["user_id"], rec["id"]) / f"{ORIGINAL}.{rec['original_ext']}"


def playback_path(rec: dict) -> Path:
    return rec_dir(rec["user_id"], rec["id"]) / PLAYBACK


def delete(user_id: str, rid: str) -> bool:
    rec = get(user_id, rid)
    if rec is None:
        return False
    db.run("DELETE FROM recordings WHERE id = ? AND user_id = ?", rid, user_id)
    shutil.rmtree(rec_dir(user_id, rid), ignore_errors=True)
    return True


def delete_all(user_id: str) -> None:
    shutil.rmtree(settings.recordings_dir / user_id, ignore_errors=True)
