const dicts: Record<Lang, Record<Key, string>> = { en, ar };

interface I18n {
  lang: Lang;
  dir: 'ltr' | 'rtl';
  t: (k: Key, vars?: Record<string, string | number>) => string;
  setLang: (l: Lang) => void;
  pick: (o: { en: string; ar: string } | null | undefined) => string;
  num: (n: number | string) => string;
}

const Ctx = createContext<I18n | null>(null);

function initialLang(): Lang {
  try {
    const s = localStorage.getItem('murattil.lang');
    if (s === 'ar' || s === 'en') return s;
  } catch {
    /* storage may be unavailable */
  }
  return navigator.language?.toLowerCase().startsWith('ar') ? 'ar' : 'en';
}

const AR_DIGITS = '٠١٢٣٤٥٦٧٨٩';
export const toArabicDigits = (n: number | string) => String(n).replace(/[0-9]/g, (d) => AR_DIGITS[+d]);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(initialLang);
  useEffect(() => {
    document.documentElement.lang = lang;
    document.documentElement.dir = lang === 'ar' ? 'rtl' : 'ltr';
  }, [lang]);
  const setLang = useCallback((l: Lang) => {
    setLangState(l);
    try {
      localStorage.setItem('murattil.lang', l);
    } catch {
      /* ignore */
    }
  }, []);
  const value = useMemo<I18n>(() => ({
    lang,
    dir: lang === 'ar' ? 'rtl' : 'ltr',
    t: (k, vars) => {
      let s = dicts[lang][k] ?? en[k] ?? k;
      if (vars) for (const [a, b] of Object.entries(vars)) s = s.replace(`{${a}}`, String(b));
      return s;
    },
    setLang,
    pick: (o) => (o ? (lang === 'ar' ? o.ar || o.en : o.en || o.ar) : ''),
    num: (n) => (lang === 'ar' ? toArabicDigits(n) : String(n)),
  }), [lang, setLang]);
  return <Ctx.Provider value={value}>{children}</Ctx.Provider>;
}

export function useI18n(): I18n {
  const v = useContext(Ctx);
  if (!v) throw new Error('I18nProvider missing');
  return v;
}
